def params(url: str, **env: str) -> StdioServerParameters:
    return StdioServerParameters(
        command=sys.executable,
        args=["-m", "upshot_mcp", "--url", url],
        env={**os.environ, "PYTHONPATH": str(CLIENTS), **env},
    )


async def session_do(url: str, work: Any, **env: str) -> Any:
    async with (
        stdio_client(params(url, **env)) as (read, write),
        ClientSession(read, write) as session,
    ):
        await session.initialize()
        return await work(session)


def listed(h: ApiHarness) -> list[dict[str, Any]]:
    with serve(h) as client:
        reply = client.post(
            "/mcp/ext/",
            json={"jsonrpc": "2.0", "id": 1, "method": "tools/list", "params": {}},
            headers={
                "Accept": "application/json, text/event-stream",
                "Authorization": f"Bearer {h.services.auth.access_key}",
            },
        )
    return list(reply.json()["result"]["tools"])


def test_the_bridge_carries_a_current_copy_of_the_meeting_tools(
    h: ApiHarness, update_goldens: bool
) -> None:
    """For an AI app that starts before Upshot. A tool changed in the app changes this."""
    tools = listed(h)
    text = (
        '"""Generated by ``pytest tests/integration/test_bridge_meetings.py --update-goldens``.\n\n'
        "The meeting tools of Upshot's /mcp/ext/, listed when Upshot cannot be asked (D98).\n"
        '"""\n\n# ruff: noqa: E501\n\nimport json\n\n'
        'TOOLS: list[dict[str, object]] = json.loads(\n    r"""\n'
        + json.dumps(tools, indent=1, ensure_ascii=False)
        + '\n"""\n)\n'
    )
    if update_goldens:
        SNAPSHOT.write_text(text, encoding="utf-8")
    assert SNAPSHOT.read_text(encoding="utf-8") == text, (
        "the bridge's copy of the meeting tools is out of date: run this test with --update-goldens"
    )


async def test_one_server_lists_both_sets_and_reads_a_meeting(h: ApiHarness) -> None:
    async def work(session: ClientSession) -> Any:
        tools = await session.list_tools()
        found = await session.call_tool("get_transcript", {"meeting_id": "m-budget"})
        return tools, found

    with serve(h):
        url = f"http://127.0.0.1:{h.services.config.server_port}"
        tools, found = await session_do(url, work)
    assert sorted(t.name for t in tools.tools) == sorted(TRANSCRIPTION + MEETINGS)
    assert not found.is_error
    assert "The marketing budget is cut by ten percent." in found.content[0].text


async def test_meeting_access_off_is_said(h: ApiHarness) -> None:
    from app.assistant import mcp

    h.services.config.set(mcp.SWITCH, False)

    async def work(session: ClientSession) -> Any:
        return await session.call_tool("search", {"query": "budget"})

    with serve(h):
        found = await session_do(f"http://127.0.0.1:{h.services.config.server_port}", work)
    assert found.content[0].text == mcp.OFF_TEXT


async def test_a_wrong_key_is_explained(h: ApiHarness) -> None:
    async def work(session: ClientSession) -> Any:
        return await session.call_tool("search", {"query": "budget"})

    with serve(h):
        url = f"http://127.0.0.1:{h.services.config.server_port}"
        found = await session_do(url, work, UPSHOT_KEY="not-the-key")
    assert found.is_error and "restart this AI app" in found.content[0].text


async def test_before_upshot_starts_the_tools_are_listed_and_say_so(tmp_path: Path) -> None:
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]  # closed again: nothing listens there

    async def work(session: ClientSession) -> Any:
        tools = await session.list_tools()
        found = await session.call_tool("search", {"query": "budget"})
        return tools, found

    tools, found = await session_do(f"http://127.0.0.1:{port}", work, UP_HOME=str(tmp_path))
    assert sorted(t.name for t in tools.tools) == sorted(TRANSCRIPTION + MEETINGS)
    assert found.is_error and "isn't running" in found.content[0].text


