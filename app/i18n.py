#: Thousands separators: the narrow no-break space is what French typography uses.
_GROUPING = {"en": ",", "he": ",", "de": ".", "es": ".", "fr": "\u202f"}


def tr(key: str, language: str, /, **fields: object) -> str:
    """``key`` in ``language``, with ``fields`` filled in. English when the language, or
    this line in it, is missing; a key nobody wrote is a bug and raises KeyError."""
    entry = MESSAGES[key]
    return entry.get(language, entry["en"]).format(**fields)


def number(value: int, language: str) -> str:
    """``value`` with the language's thousands separator: 6,700 / 6.700 / 6 700."""
    return f"{value:,}".replace(",", _GROUPING.get(language, ","))
